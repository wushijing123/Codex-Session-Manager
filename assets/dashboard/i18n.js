  const queryLocale = new URLSearchParams(window.location.search).get("lang");
  let locale = queryLocale === "en" || localStorage.getItem(STORAGE_KEY) === "en" ? "en" : "zh-CN";

  function t(source, variables = {}) {
    const template = locale === "en" ? (english[source] || source) : source;
    return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (_, key) => String(variables[key] ?? `{${key}}`));
  }

  function setLocale(next) {
    locale = next === "en" ? "en" : "zh-CN";
    localStorage.setItem(STORAGE_KEY, locale === "en" ? "en" : "zh-CN");
    return locale;
  }

  window.SessionManagerI18n = {
    has: source => Object.prototype.hasOwnProperty.call(english, source),
    locale: () => locale,
    setLocale,
    t
  };
